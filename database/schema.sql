-- Agriculture Information System - schema (Supabase PostgreSQL)
-- Run this whole file once in Supabase -> SQL Editor.

-- ---------- Lookup tables ----------
CREATE TABLE roles (
    role_id   SMALLINT PRIMARY KEY,
    role_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE soil_types (
    soil_type_id   SMALLINT PRIMARY KEY,
    soil_type_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE irrigation_types (
    irrigation_type_id   SMALLINT PRIMARY KEY,
    irrigation_type_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE crop_categories (
    crop_category_id SMALLINT PRIMARY KEY,
    category_name    VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE seasons (
    season_id   SMALLINT PRIMARY KEY,
    season_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE planting_statuses (
    status_id   SMALLINT PRIMARY KEY,
    status_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE quality_grades (
    grade_id   SMALLINT PRIMARY KEY,
    grade_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE harvest_remarks (
    remark_id          SMALLINT PRIMARY KEY,
    remark_description VARCHAR(200) NOT NULL UNIQUE
);

-- ---------- Users ----------
CREATE TABLE users (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL CHECK (btrim(username) <> ''),
    full_name     VARCHAR(100) NOT NULL CHECK (btrim(full_name) <> ''),
    password_hash VARCHAR(255) NOT NULL,
    role_id       SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_username ON users (lower(username));

-- ---------- Main tables ----------
CREATE TABLE farmer (
    farmer_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(50)  NOT NULL CHECK (btrim(first_name) <> ''),
    last_name       VARCHAR(50)  NOT NULL CHECK (btrim(last_name) <> ''),
    contact_number  VARCHAR(20)  NOT NULL CHECK (contact_number ~ '^[0-9+() -]{7,20}$'),
    address         VARCHAR(150) NOT NULL CHECK (btrim(address) <> ''),
    date_registered DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_by      INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT uq_farmer_person UNIQUE (first_name, last_name, contact_number)
);

CREATE TABLE farm (
    farm_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id          INTEGER NOT NULL REFERENCES farmer(farmer_id) ON DELETE RESTRICT,
    farm_name          VARCHAR(100) NOT NULL CHECK (btrim(farm_name) <> ''),
    location           VARCHAR(150) NOT NULL CHECK (btrim(location) <> ''),
    area_hectares      NUMERIC(8,2) NOT NULL CHECK (area_hectares > 0),
    soil_type_id       SMALLINT NOT NULL REFERENCES soil_types(soil_type_id) ON DELETE RESTRICT,
    irrigation_type_id SMALLINT NOT NULL REFERENCES irrigation_types(irrigation_type_id) ON DELETE RESTRICT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by         INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_by         INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT uq_farm_name_per_farmer UNIQUE (farmer_id, farm_name)
);

CREATE TABLE crop (
    crop_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name           VARCHAR(80) NOT NULL CHECK (btrim(crop_name) <> ''),
    variety             VARCHAR(80) NOT NULL CHECK (btrim(variety) <> ''),
    crop_category_id    SMALLINT NOT NULL REFERENCES crop_categories(crop_category_id) ON DELETE RESTRICT,
    growing_period_days INTEGER NOT NULL CHECK (growing_period_days BETWEEN 1 AND 1000),
    season_id           SMALLINT NOT NULL REFERENCES seasons(season_id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_by          INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT uq_crop_variety UNIQUE (crop_name, variety)
);

CREATE TABLE planting (
    planting_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id               INTEGER NOT NULL REFERENCES farm(farm_id) ON DELETE RESTRICT,
    crop_id               INTEGER NOT NULL REFERENCES crop(crop_id) ON DELETE RESTRICT,
    planting_date         DATE NOT NULL,
    area_planted          NUMERIC(8,2) NOT NULL CHECK (area_planted > 0),
    seed_quantity         NUMERIC(8,2) NOT NULL CHECK (seed_quantity > 0),
    expected_harvest_date DATE NOT NULL,
    status_id             SMALLINT NOT NULL REFERENCES planting_statuses(status_id) ON DELETE RESTRICT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_by            INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT ck_planting_dates CHECK (expected_harvest_date > planting_date)
);

CREATE TABLE harvest (
    harvest_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id          INTEGER NOT NULL REFERENCES planting(planting_id) ON DELETE RESTRICT,
    harvest_date         DATE NOT NULL,
    quantity_kg          NUMERIC(10,2) NOT NULL CHECK (quantity_kg > 0),
    selling_price_per_kg NUMERIC(10,2) NOT NULL CHECK (selling_price_per_kg >= 0),
    grade_id             SMALLINT NOT NULL REFERENCES quality_grades(grade_id) ON DELETE RESTRICT,
    remark_id            SMALLINT NOT NULL REFERENCES harvest_remarks(remark_id) ON DELETE RESTRICT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_by           INTEGER REFERENCES users(user_id) ON DELETE SET NULL
);

-- ---------- Indexes on foreign keys ----------
CREATE INDEX ix_farm_farmer      ON farm (farmer_id);
CREATE INDEX ix_planting_farm    ON planting (farm_id);
CREATE INDEX ix_planting_crop    ON planting (crop_id);
CREATE INDEX ix_planting_status  ON planting (status_id);
CREATE INDEX ix_harvest_planting ON harvest (planting_id);
CREATE INDEX ix_harvest_date     ON harvest (harvest_date);

-- ---------- updated_at trigger ----------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_updated    BEFORE UPDATE ON users    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_farmer_updated   BEFORE UPDATE ON farmer   FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_farm_updated     BEFORE UPDATE ON farm     FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_crop_updated     BEFORE UPDATE ON crop     FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_planting_updated BEFORE UPDATE ON planting FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_harvest_updated  BEFORE UPDATE ON harvest  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------- Security: block the public Supabase API ----------
-- The PHP app connects with the database owner role (it bypasses RLS).
-- Enabling RLS with no policies means the public anon key cannot read these tables.
