ALTER TABLE soil_types        ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_types  ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_categories   ENABLE ROW LEVEL SECURITY;
ALTER TABLE seasons           ENABLE ROW LEVEL SECURITY;
ALTER TABLE planting_statuses ENABLE ROW LEVEL SECURITY;
ALTER TABLE quality_grades    ENABLE ROW LEVEL SECURITY;
ALTER TABLE harvest_remarks   ENABLE ROW LEVEL SECURITY;
ALTER TABLE users             ENABLE ROW LEVEL SECURITY;
ALTER TABLE farmer            ENABLE ROW LEVEL SECURITY;
ALTER TABLE farm              ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop              ENABLE ROW LEVEL SECURITY;
ALTER TABLE planting          ENABLE ROW LEVEL SECURITY;
ALTER TABLE harvest           ENABLE ROW LEVEL SECURITY;
